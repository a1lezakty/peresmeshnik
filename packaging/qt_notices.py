"""Writes packaging/licenses/Qt-third-party.txt: the notices of the third-party code built into the Qt libraries the
app ships (Qt6Core, Qt6Gui, Qt6Widgets, Qt6Network, Qt6Svg and their plugins: PCRE2, FreeType, HarfBuzz, zlib,
libpng, the Unicode data...), from the qt_attribution.json files of Qt's own sources at the tag of that version.
Run it (network, stdlib only) when PySide6 moves to another Qt; packaging/licenses.py fails the build until then:

    python packaging/qt_notices.py 6.12.0
"""
import json
import posixpath
import re
import sys
import urllib.request
from pathlib import Path

VERSION = sys.argv[1]
REPOS = ('qtbase', 'qtsvg')  # qtimageformats: its plugins (qtiff, qwebp...) are not shipped (the .spec files drop them)
# not in the Windows or macOS build: Linux and other platforms, tests and build tools
SKIP = re.compile(r'^(cmake|tests|util|src/testlib|src/testinternal'
                  r'|src/3rdparty/(android|gradle|wasm|wayland|xcb))/')
OUT = Path(__file__).resolve().parent / 'licenses' / 'Qt-third-party.txt'


def get(url: str) -> str:
    with urllib.request.urlopen(url, timeout=60) as r:
        return r.read().decode('utf-8')


def ids(expr: str) -> list[str]:
    """The license ids to show: the first choice of an OR, every part of an AND or WITH."""
    first = expr.replace('(', '').replace(')', '').split(' OR ')[0]
    return [p.strip() for p in re.split(r' AND | WITH ', first) if p.strip()]


entries, texts = [], {}  # texts: name -> text, each once
for repo in REPOS:
    raw = f'https://raw.githubusercontent.com/qt/{repo}/v{VERSION}'
    tree = json.loads(get(f'https://api.github.com/repos/qt/{repo}/git/trees/v{VERSION}?recursive=1'))
    assert not tree['truncated'], f'{repo}: the tree listing is cut short'
    for path in sorted(e['path'] for e in tree['tree'] if e['path'].endswith('qt_attribution.json')):
        if SKIP.match(path):
            continue
        here = path.rsplit('/', 1)[0]
        doc = json.loads(get(f'{raw}/{path}'), strict=False)  # some have line breaks inside strings
        for a in doc if isinstance(doc, list) else [doc]:
            own = a.get('LicenseFile') or []  # its own file, with its copyright; else Qt's text of each license id
            own = [posixpath.normpath(f'{here}/{f}') for f in ([own] if isinstance(own, str) else own)]
            files = ([(f'{repo}/{f}', f'{raw}/{f}') for f in own]
                     or [(f'LICENSES/{i}.txt', f'{raw}/LICENSES/{i}.txt') for i in ids(a.get('LicenseId', ''))])
            for name, url in files:
                if name not in texts:
                    texts[name] = get(url).strip()
            names = [name for name, _ in files]
            c = a.get('Copyright') or (get(f'{raw}/{here}/{a["CopyrightFile"]}') if a.get('CopyrightFile') else '')
            c = '\n'.join(c) if isinstance(c, list) else c
            entries.append(f'{a["Name"]} {a.get("Version", "")}'.strip() + f' ({repo}/{here})\n'
                           f'{a.get("QtUsage", "").strip()}\n{a.get("Homepage", "")}\n'
                           f'{c.strip()}\nLicense: {a.get("License", "")} ({a.get("LicenseId", "")}): '
                           f'see {", ".join(names)} below\n')

OUT.write_text(f'''Third-party code in Qt {VERSION}
(the Qt libraries in this app are LGPL-3.0-only: see the PySide6_Essentials folder; their source is named in
LGPL-SOURCE.txt). Generated by packaging/qt_notices.py from the qt_attribution.json files of
https://github.com/qt/qtbase and https://github.com/qt/qtsvg at tag v{VERSION}; Linux-only, Android, WebAssembly,
test and build-tool code left out.

{'-' * 100}
''' + f'\n{"-" * 100}\n'.join(entries) + ''.join(f'\n{"=" * 100}\n{name}\n{"=" * 100}\n{text}\n'
                                               for name, text in texts.items()), 'utf-8')
print(f'{OUT}: {len(entries)} components, {len(texts)} license texts')
